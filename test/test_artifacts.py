def test_the_record_field_and_its_lifetime(tmp_path):
    """AC-613, AC-622, AC-623 and the rewind copy: the entry lands on the
    NEXT message of its role only; other messages are byte-identical in
    shape; delete removes the folder; a rewind's copy keeps its own."""
    store = art.ArtifactStore(tmp_path / "artifacts")
    chats = ChatStore(tmp_path / "chats", artifacts=store)
    cid = chats.current()["id"]
    src = tmp_path / "a.csv"
    src.write_text("a,b\n1,2\n", encoding="utf-8")
    chats.append(cid, "user", "show me")
    entry = store.snapshot(cid, src)
    chats.show(cid, "assistant", entry)
    chats.append(cid, "user", "not this one")      # wrong role: untouched
    chats.append(cid, "assistant", "here it is")
    chats.append(cid, "assistant", "and more")
    msgs = chats.find(cid)["messages"]
    assert [("artifacts" in m) for m in msgs] == [False, False, True, False]
    assert msgs[2]["artifacts"] == [entry]
    assert set(msgs[3]) == {"id", "role", "content", "timestamp"}  # AC-623
    snap = chats.rewind(msgs[1]["id"])["snapshot"]
    assert store.find(snap, entry["id"]) is not None
    assert chats.delete(cid)
    assert store.find(cid, entry["id"]) is None
    assert store.find(snap, entry["id"]) is not None


