def _harness_hub(tmp_path, monkeypatch):
    (tmp_path / "registry.json").write_text('{"providers": {}}',
                                            encoding="utf-8")
    (tmp_path / "settings.json").write_text(json.dumps(
        {"harness": "fake", "hotkeys_enabled": False}), encoding="utf-8")
    monkeypatch.setenv("BUTLER_STATE", str(tmp_path))
    monkeypatch.setattr(butlerd, "PI_REGISTRY", tmp_path / "registry.json")
    monkeypatch.setenv("BUTLER_ENDPOINTER", "none")
    monkeypatch.delenv("BUTLER_SELF_URL", raising=False)
    return butlerd.build_hub({"adapters": {"asr": "fake", "tts": "fake",
                                           "brain": "harness_only"}})


class _Shown:
    """A harness hub on three real listeners, one project row, one chat in
    it with a message on disk, and a page session watching the frames."""

    def __init__(self, tmp_path, monkeypatch):
        self.tmp = tmp_path
        self.hub = _harness_hub(tmp_path, monkeypatch)
        # A SIBLING of tmp_path: tmp_path is BUTLER_STATE, the records, and
        # a project inside the records is (rightly) refused by the guard.
        self.project = tmp_path.parent / f"{tmp_path.name}-proj"
        self.project.mkdir()
        self.hub.shortcuts.upsert(sid="", path=str(self.project),
                                  label="PROJ")
        self.row = next(r.id for r in self.hub.shortcuts.all()
                        if r.label == "PROJ")
        self.three = _Three(self.hub, monkeypatch)

    async def __aenter__(self):
        await self.three.__aenter__()
        self.chat = (await self.hub.new_conversation(self.row))["id"]
        self.hub.brain.host.record(self.chat, "user", "show me")
        self.page = attach_session(self.hub, name="page")
        return self

    async def __aexit__(self, *exc):
        await self.three.__aexit__(*exc)

    async def show(self, tool, args, kind=hub_mod.LOCAL, chat=None):
        async with self.three.http.post(
                self.three.url(kind, "/api/artifacts/show"),
                headers=await self.three.who(kind),
                json={"tool": tool, "args": args,
                      "chat": chat or self.chat}) as r:
            return r.status, await r.json()

    async def get(self, path, kind=hub_mod.PROXIED, headers=None):
        async with self.three.http.get(
                self.three.url(kind, path),
                headers={**await self.three.who(kind), **(headers or {})}) as r:
            return r.status, dict(r.headers), await r.read()

    def frames(self):
        return [json.loads(m) for m in self.page.ws.sent
                if isinstance(m, str)
                and json.loads(m).get("type") == "artifact"]


