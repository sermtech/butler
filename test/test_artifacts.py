@pytest.mark.asyncio
async def test_a_dropped_file_is_added_never_replaced(tmp_path,
                                                      monkeypatch):
    """RC-13: an upload writes a NEW file into the named folder; an
    existing name is 409 and untouched; a path name, a secret name, a
    skipped name and an oversize body are refused and write nothing."""
    async with _Shown(tmp_path, monkeypatch) as t:
        (t.project / "docs").mkdir()
        (t.project / "docs" / "keep.txt").write_text("orig",
                                                     encoding="utf-8")

        async def up(path, name, data, kind=hub_mod.PROXIED):
            async with t.three.http.post(
                    t.three.url(kind, f"/api/project/{t.row}/upload"),
                    headers=await t.three.who(kind),
                    params={"path": path, "name": name}, data=data) as r:
                return r.status, await r.json()
        status, body = await up("docs", "new.png", png())
        assert status == 200 and body == {"path": "docs/new.png",
                                          "size": len(png())}
        assert (t.project / "docs" / "new.png").read_bytes() == png()
        status, _ = await up("docs", "keep.txt", b"evil")
        assert status == 409
        assert (t.project / "docs" / "keep.txt").read_text() == "orig"
        for path, name, code in (("docs", "../up.txt", 400),
                                 ("docs", "a/b.txt", 400),
                                 ("docs", ".env", 403),
                                 ("", "node_modules", 403),
                                 ("..", "x.txt", 400),
                                 ("docs/keep.txt", "x.txt", 400),
                                 # Windows drops a trailing space or dot,
                                 # so these would land as `.env` and
                                 # `node_modules` (review 2026-10-29).
                                 ("docs", ".env ", 400),
                                 ("docs", ".env.", 400),
                                 ("", "node_modules ", 400)):
            status, _ = await up(path, name, b"x")
            assert status == code, (path, name, status)
        assert not (t.project / "docs" / ".env").exists()
        assert not (t.project / "node_modules").exists()
        monkeypatch.setattr(butlerd.files_mod, "MAX_UPLOAD", 1000)
        status, _ = await up("", "big.bin", b"\x00" * 200_000)
        assert status == 413
        assert not (t.project / "big.bin").exists()
        assert not (tmp_path / "up.txt").exists()


