class Recorder:
    """A brain that keeps the whole TurnContext, because the question here is
    what ELSE was in it -- `test_ambient.py`'s rule."""

    def __init__(self):
        self.seen = []

    async def turn(self, text, ctx):
        self.seen.append((text, ctx))
        yield ports.Say("Noted.", tier="reflex")
        yield ports.Done("reflex")

    async def abort(self, turn_id):
        pass

    async def warm(self):
        pass

    @property
    def info(self):
        return {"engine": "recorder"}


@pytest.mark.asyncio
async def test_the_next_turn_gets_it_and_the_utterance_is_UNTOUCHED(
        tmp_path, monkeypatch):
    """AC-199 and AC-202 in one, because they are one rule.

    The attachment reaches the brain on the CONTEXT, and what the owner said
    is byte-for-byte what they said -- a filename folded into the utterance is
    a word they did not speak, and it would enter the record as one.
    """
    from test_typed_turn import type_at

    hub = _hub(tmp_path)
    hub.brain = Recorder()
    s = attach_session(hub)

    async with _http(hub, monkeypatch) as client:
        await _post(client, PNG, name="the kitchen.png")
    await type_at(hub, s, "what is in this photo")

    text, ctx = hub.brain.seen[-1]
    assert text == "what is in this photo", (
        f"the utterance was rewritten: {text!r}")
    assert len(ctx.attachments) == 1, (
        f"the attachment did not reach the turn: {ctx.attachments}")
    assert ctx.attachments[0].name == "the kitchen.png", ctx.attachments[0]
    assert s.attachments == [], "it was not cleared after the turn took it"


