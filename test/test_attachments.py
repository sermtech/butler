"""Showing Butler a file. AC-197..AC-204, `docs/attachments.md`.

    POST /api/attach?device=<id>&name=<filename>   the FILE as the body

Three properties carry this file and each is a way the feature could lie.

**The TYPE is sniffed from the bytes** (AC-198). Both the filename and the
`Content-Type` header belong to the caller, and this route writes a file a
coding agent may later be pointed at -- so the fixture that matters is the one
whose extension DISAGREES with its contents, and the assertion is that the
bytes won.

**An attachment is PENDING ON THE SESSION and is taken by the next turn**
(AC-199), spoken or typed. A `typed`-only field would have made "show Butler
this and ask about it out loud" impossible, so the test drives a real turn and
reads `ctx.attachments` off the brain -- and asserts that the UTTERANCE is
untouched, which is `test_ambient.py`'s rule for `test_ambient.py`'s reason: a
filename folded into what the owner said is a word they did not speak.

**Documents are READ before they are looked at** (AC-200). The PDF and the
docx here are generated by the same libraries that read them, so the test
asserts the pipeline rather than a checked-in binary nobody can regenerate.
"""
