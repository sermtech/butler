# The smallest valid PNG: an 8-bit greyscale 1x1. Written out rather than
# checked in, so nothing here depends on a binary fixture somebody has to
# trust.
PNG = bytes.fromhex(
    "89504e470d0a1a0a0000000d49484452000000010000000108000000003a7e9b55"
    "0000000a4944415408d76360000000020001e221bc330000000049454e44ae4260"
    "82")


def make_pdf(text: str) -> bytes:
    """A one-page PDF with a real text layer, built by pypdf's own writer."""
    from pypdf import PdfWriter
    from pypdf.generic import (ArrayObject, DecodedStreamObject, DictionaryObject,
                               NameObject, NumberObject)
    writer = PdfWriter()
    page = writer.add_blank_page(width=200, height=200)
    stream = DecodedStreamObject()
    stream.set_data(f"BT /F1 12 Tf 20 100 Td ({text}) Tj ET".encode("ascii"))
    font = DictionaryObject({
        NameObject("/Type"): NameObject("/Font"),
        NameObject("/Subtype"): NameObject("/Type1"),
        NameObject("/BaseFont"): NameObject("/Helvetica")})
    page[NameObject("/Contents")] = writer._add_object(stream)
    page[NameObject("/Resources")] = DictionaryObject({
        NameObject("/Font"): DictionaryObject({
            NameObject("/F1"): writer._add_object(font)})})
    page[NameObject("/MediaBox")] = ArrayObject(
        [NumberObject(0), NumberObject(0), NumberObject(200), NumberObject(200)])
    buf = io.BytesIO()
    writer.write(buf)
    return buf.getvalue()


def make_docx(text: str) -> bytes:
    import docx
    d = docx.Document()
    d.add_paragraph(text)
    buf = io.BytesIO()
    d.save(buf)
    return buf.getvalue()


def _hub(tmp_path, **kw):
    hub = make_hub(tmp_path, **kw)
    hub.tts = QuietTts()
    hub.settings = Settings(tmp_path / "settings.json")
    hub.attachments = attach_mod.AttachmentStore(tmp_path / "attachments")
    return hub


@contextlib.asynccontextmanager
async def _http(hub, monkeypatch):
    from aiohttp.test_utils import TestClient, TestServer

    monkeypatch.setattr(butlerd, "build_hub", lambda cfg: hub)
    client = TestClient(TestServer(butlerd.make_app({})))
    await client.start_server()
    try:
        yield client
    finally:
        await client.close()


async def _post(client, data, name="photo.png", device="desk"):
    answer = await client.post(
        f"/api/attach?device={device}&name={name}", data=data)
    return answer.status, await answer.json()


