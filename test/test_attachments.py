@pytest.mark.asyncio
async def test_a_file_is_stored_and_pends_on_the_session(tmp_path, monkeypatch):
    """AC-197 and AC-199. The bytes land on disk and the SESSION holds it.

    On the session rather than on a turn, because there is no turn yet when a
    file is attached -- which is the whole reason this is not a field on the
    `typed` frame.
    """
    hub = _hub(tmp_path)
    s = attach_session(hub)

    async with _http(hub, monkeypatch) as client:
        status, doc = await _post(client, PNG)

    assert status == 200, doc
    assert doc["kind"] == "image" and doc["media_type"] == "image/png", doc
    assert doc["bytes"] == len(PNG), doc
    assert doc["name"] == "photo.png", doc
    assert len(s.attachments) == 1, (
        f"the attachment is not pending on the session that sent it: "
        f"{s.attachments}")
    # `.att`: what pends is a `Pending(chat, att)` pair since AC-247, and
    # the chat here is "" because this hub's brain holds no conversations.
    stored = Path(s.attachments[0].att.path)
    assert stored.read_bytes() == PNG, "the bytes on disk are not the bytes sent"
    assert stored.parent == tmp_path / "attachments", stored


