def _converse(server, **kw):
    from conftest import StubResolver
    from daemon.adapters.brain_endpoint import EndpointConverse
    return EndpointConverse(StubResolver(server.base_url, **kw))


async def _drain(brain, text, ctx):
    said = []
    async for intent in brain.turn(text, ctx):
        if isinstance(intent, ports.Say):
            said.append(intent.text)
    return said


@pytest.mark.asyncio
async def test_an_image_rides_on_the_USER_message_as_a_content_part(
        tmp_path, fake_openai):
    """AC-202 on the WIRE, which is the only place it can be checked.

    "The image was attached" and "the image was SENT" are different claims,
    and the second one is the criterion -- a brain that read `ctx.attachments`
    and built a request without it would satisfy every other test here. So
    this asserts the body the server actually received.
    """
    import base64

    store = attach_mod.AttachmentStore(tmp_path / "a")
    att = store.add(PNG, "kitchen.png", "text")
    fake_openai.answer("I can see a kitchen.")
    brain = _converse(fake_openai)

    said = await _drain(brain, "what is in this photo",
                        ports.TurnContext(turn_id=1, mode="secretary",
                                          attachments=(att,)))

    assert said == ["I can see a kitchen."], said
    body = fake_openai.asks[-1].body
    user = [m for m in body["messages"] if m["role"] == "user"][-1]
    assert isinstance(user["content"], list), (
        f"the image never reached the wire: {user}")
    assert [part["type"] for part in user["content"]] == ["text", "image_url"]
    assert user["content"][0]["text"] == "what is in this photo", (
        "the utterance was rewritten on its way to the model")
    url = user["content"][1]["image_url"]["url"]
    assert url.startswith("data:image/png;base64,"), url[:40]
    assert base64.b64decode(url.split(",", 1)[1]) == PNG, (
        "the bytes on the wire are not the bytes that were attached")


